import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const snippetPath = path.join(root, 'chatgpt-toolbox/scripts/refactor-runtime-verification-console-snippet.js');
const outPath = path.join(root, 'exports/for_chatgpt/refactor_runtime_oneshot_verify_download.js');

const snippet = fs.readFileSync(snippetPath, 'utf8');
const body = snippet.replace(/^\/\*\*[\s\S]*?\*\/\s*/, '');

const footer = `
    // --- harvest + export bundle ---
    showToolboxLogs();
    const harvestAll = collectToolboxLogLines();
    const harvest = {
      at: new Date().toISOString(),
      toolboxVersion: typeof globalThis.__CGPT_TOOLBOX_VERSION__ !== 'undefined'
        ? globalThis.__CGPT_TOOLBOX_VERSION__
        : null,
      totalLines: harvestAll.length,
      sendMessage: filterLines(harvestAll, /\\[SEND_PIPELINE\\]/),
      sendCopyHotkey: filterLines(harvestAll, /SKIP_LOCAL_QUEUE_FOR_SEND_COPY_HOTKEY|SEND_PIPELINE|send-copy-hotkey/i),
      closedLoop: filterLines(harvestAll, /\\[CLOSED_LOOP\\]/),
      upload: filterLines(harvestAll, /\\[UPLOAD\\]|\\[UPLOAD_RUNNER\\]|\\[UPLOAD_SEND_FLOW\\]|\\[BRIDGE\\]\\[UPLOAD\\]/),
      edgeCases: filterLines(harvestAll, /empty_text|composer_empty|duplicate|another-send-running|blocked|runId=/i),
      candidateViolations: filterLines(harvestAll, /candidate=1/),
      tail: harvestAll.slice(-120),
    };
    report.sections.manualHarvest = harvest;
    const exportPayload = { summary, report, harvest };
    const exportText = [
      '# Refactor runtime verification — browser (2026-06-04)',
      '# Generated by refactor_runtime_oneshot_verify_download.js',
      '# === REFACTOR RUNTIME VERIFY DONE ===',
      '',
      JSON.stringify(exportPayload, null, 2),
      '',
      '# --- C1 send-message logs ---',
      ...(harvest.sendMessage.length ? harvest.sendMessage : ['# (none captured)']),
      '',
      '# --- C2 send-copy-hotkey logs ---',
      ...(harvest.sendCopyHotkey.length ? harvest.sendCopyHotkey : ['# (none captured)']),
      '',
      '# --- C3 closed-loop success ---',
      ...filterLines(harvest.closedLoop, /DISPATCH_RESULT.*ok=1|ok=1/).slice(-10),
      '',
      '# --- C4 closed-loop fail ---',
      ...filterLines(harvest.closedLoop, /ok=0|DISPATCH_FAILED/).slice(-10),
      ...(report.sections.closedLoopFail && report.sections.closedLoopFail.lines
        ? report.sections.closedLoopFail.lines
        : []),
      '',
      '# --- C5 upload ---',
      ...(harvest.upload.length ? harvest.upload : ['# add file + click #cgpt-upload-start if empty']),
      '',
      '# --- C6 edge cases ---',
      ...(harvest.edgeCases.length ? harvest.edgeCases : ['# (none captured)']),
      '',
      '# candidate violations:',
      ...(harvest.candidateViolations.length ? harvest.candidateViolations : ['# none']),
    ].join('\\n');
    console.log('\\n=== REFACTOR RUNTIME EXPORT TEXT BEGIN ===\\n');
    console.log(exportText);
    console.log('\\n=== REFACTOR RUNTIME EXPORT TEXT END ===\\n');
    try {
      if (typeof copy === 'function') {
        copy(exportText);
        console.log('[REFACTOR_VERIFY] copy() invoked — save to exports/for_chatgpt/refactor_runtime_verification_20260604_runtime.txt');
      }
    } catch (copyErr) {
      console.warn('[REFACTOR_VERIFY] copy() unavailable', copyErr);
    }
    try {
      const blob = new Blob([exportText], { type: 'text/plain;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = 'refactor_runtime_verification_20260604_runtime.txt';
      document.body.appendChild(a);
      a.click();
      a.remove();
      URL.revokeObjectURL(url);
      console.log('[REFACTOR_VERIFY] download triggered');
    } catch (dlErr) {
      console.error('[REFACTOR_VERIFY] download failed', dlErr);
    }
    return exportPayload;
`;

const anchorRe = /    return \{ summary, report \};\r?\n  \} catch \(err\) \{/;

if (!anchorRe.test(body)) {
  throw new Error('Snippet anchor not found — refactor-runtime-verification-console-snippet.js changed');
}

const mergedBody = body.replace(anchorRe, footer + '\n  } catch (err) {');

const header = `/**
 * ONE-SHOT refactor runtime verify + export
 * Paste entire file in DevTools Console on logged-in https://chatgpt.com
 * Prerequisites: Tampermonkey ONLY chatgpt-toolbox/dist/client.user.js; toolbox open; #cgpt-log-clear
 * Output: === REFACTOR RUNTIME VERIFY DONE === + auto-download refactor_runtime_verification_20260604_runtime.txt
 */
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, header + mergedBody, 'utf8');
console.log('[OK] Wrote', outPath);
